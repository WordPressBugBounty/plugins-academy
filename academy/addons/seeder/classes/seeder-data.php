	/**
	 * Build the `video_source` meta value for a given lesson source type.
	 *
	 * @param string $source        One of text|youtube|vimeo|html5|external|embedded|short_code.
	 * @param int    $attachment_id Attachment id to use for the self-hosted (html5) source.
	 *
	 * @return array{type:string,url?:string,id?:int}|array
	 */
	public static function video_source_for( $source, $attachment_id = 0 ) {
		switch ( $source ) {
			case 'youtube':
				return [
					'type' => 'youtube',
					'url'  => self::SAMPLE_YOUTUBE_URL,
				];
			case 'vimeo':
				return [
					'type' => 'vimeo',
					'url'  => self::SAMPLE_VIMEO_URL,
				];
			case 'html5':
				// Needs a real attachment; fall back to the external URL when the
				// sideload failed so the lesson still plays.
				if ( $attachment_id > 0 ) {
					return [
						'type' => 'html5',
						'id'   => $attachment_id,
					];
				}
				return [
					'type' => 'external',
					'url'  => self::SAMPLE_VIDEO_URL,
				];
			case 'external':
				return [
					'type' => 'external',
					'url'  => self::SAMPLE_VIDEO_URL,
				];
			case 'embedded':
				return [
					'type' => 'embedded',
					'url'  => '<iframe width="560" height="315" src="https://www.youtube.com/embed/YE7VzlLtp-4" title="Sample embedded video" frameborder="0" allowfullscreen></iframe>',
				];
			case 'short_code':
				return [
					'type' => 'short_code',
					'url'  => '[embed]' . self::SAMPLE_YOUTUBE_URL . '[/embed]',
				];
			case 'text':
			default:
				return [];
		}//end switch
	}

