	/**
	 * Create a placeholder image attachment (no network) — used as both the
	 * seeded course's featured image and every one of its lessons'
	 * featured/attachment image. Always prefers sideloading the plugin's own
	 * bundled add-ons banner artwork (a real, designed image) over a GD-drawn
	 * coloured tile with a label, which only falls back to a blank 1×1 pixel
	 * once GD is unavailable — that blank tile still attaches/sets as the
	 * featured image "successfully" but shows nothing wherever it's used.
	 *
	 * @param string $label   Text drawn on the tile (GD fallback only).
	 * @param int    $variant Colour variant selector (GD fallback only).
	 *
	 * @return int Attachment id, or 0 on failure.
	 */
	public static function create_placeholder_image( $label = 'Academy', $variant = 0 ) {
		$attachment_id = self::bundled_banner_image();
		if ( $attachment_id ) {
			return $attachment_id;
		}

		// Fallback, only if the bundled artwork couldn't be sideloaded
		// (missing file, disk write failure, etc.) and GD happens to be
		// available.
		return self::gd_placeholder_image( $label, $variant );
	}

	/**
	 * GD-drawn coloured tile with a label — the fallback when the bundled
	 * banner artwork (see bundled_banner_image()) can't be used.
	 *
	 * @param string $label   Text drawn on the tile.
	 * @param int    $variant Colour variant selector.
	 *
	 * @return int Attachment id, or 0 on failure.
	 */
	private static function gd_placeholder_image( $label, $variant ) {
		if ( ! function_exists( 'imagecreatetruecolor' ) ) {
			return 0;
		}

		$bytes = self::placeholder_png_bytes( $label, $variant );
		if ( '' === $bytes ) {
			return 0;
		}

		$filename = 'academy-seeder-' . sanitize_title( $label . '-' . $variant ) . '.png';
		$upload   = wp_upload_bits( $filename, null, $bytes );
		if ( ! empty( $upload['error'] ) || empty( $upload['file'] ) ) {
			return 0;
		}

		$attachment_id = wp_insert_attachment( [
			'post_mime_type' => 'image/png',
			'post_title'     => sanitize_file_name( $label ),
			'post_status'    => 'inherit',
		], $upload['file'] );

		if ( is_wp_error( $attachment_id ) || ! $attachment_id ) {
			return 0;
		}

		if ( ! function_exists( 'wp_generate_attachment_metadata' ) ) {
			require_once ABSPATH . 'wp-admin/includes/image.php';
		}
		$meta = wp_generate_attachment_metadata( $attachment_id, $upload['file'] );
		wp_update_attachment_metadata( $attachment_id, $meta );

		return (int) $attachment_id;
	}

	/**
	 * GD-less fallback: sideloads assets/images/addons-pro-banner.svg (the
	 * "Unlock Every Add-On with One Price" background on the Add-ons page —
	 * a purely abstract gradient graphic, no promotional text baked into the
	 * file itself) as the seeded course's featured image.
	 *
	 * @return int Attachment id, or 0 on failure.
	 */
	private static function bundled_banner_image() {
		$source = ACADEMY_ASSETS_DIR_PATH . 'images/addons-pro-banner.svg';
		if ( ! file_exists( $source ) ) {
			return 0;
		}

		// phpcs:disable WordPressVIPMinimum.Performance.FetchingRemoteData.FileGetContentsUnknown -- local file, not a remote URL
		$bytes = file_get_contents( $source ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		// phpcs:enable WordPressVIPMinimum.Performance.FetchingRemoteData.FileGetContentsUnknown
		if ( false === $bytes || '' === $bytes ) {
			return 0;
		}

		// wp_upload_bits() checks the file extension against the site's
		// allowed mime types, and SVG isn't in WordPress's default list —
		// allow it only for this one sideload of a trusted, bundled plugin
		// asset (never for user-supplied uploads).
		$allow_svg = function ( $mimes ) {
			$mimes['svg'] = 'image/svg+xml';
			return $mimes;
		};
		add_filter( 'upload_mimes', $allow_svg ); // phpcs:ignore WordPressVIPMinimum.Hooks.RestrictedHooks.upload_mimes -- dev-only seeder, filter removed right after
		$upload = wp_upload_bits( 'academy-seeder-course-banner.svg', null, $bytes );
		remove_filter( 'upload_mimes', $allow_svg );

		if ( ! empty( $upload['error'] ) || empty( $upload['file'] ) ) {
			return 0;
		}

		$attachment_id = wp_insert_attachment( [
			'post_mime_type' => 'image/svg+xml',
			'post_title'     => __( 'Sample Course Banner', 'academy' ),
			'post_status'    => 'inherit',
		], $upload['file'] );

		if ( is_wp_error( $attachment_id ) || ! $attachment_id ) {
			return 0;
		}

		return (int) $attachment_id;
	}

	/**
	 * Download a remote video and store it as an attachment (self-hosted lesson).
	 * Best-effort: returns 0 on any failure (no network, blocked host, etc.).
	 *
	 * @param string $url Remote video URL.
	 *
	 * @return int Attachment id, or 0.
	 */
	public static function sideload_video( $url ) {
		if ( ! function_exists( 'download_url' ) ) {
			require_once ABSPATH . 'wp-admin/includes/file.php';
		}

		$tmp = download_url( $url, 30 );
		if ( is_wp_error( $tmp ) ) {
			return 0;
		}

		$file_array = [
			'name'     => basename( wp_parse_url( $url, PHP_URL_PATH ) ),
			'tmp_name' => $tmp,
		];

		if ( ! function_exists( 'media_handle_sideload' ) ) {
			require_once ABSPATH . 'wp-admin/includes/media.php';
			require_once ABSPATH . 'wp-admin/includes/image.php';
		}

		$attachment_id = media_handle_sideload( $file_array, 0 );

		if ( is_wp_error( $attachment_id ) ) {
			if ( file_exists( $tmp ) ) {
				wp_delete_file( $tmp );
			}
			return 0;
		}

		return (int) $attachment_id;
	}

	/**
	 * Raw PNG bytes for a placeholder tile. Only called once the caller has
	 * already confirmed GD (imagecreatetruecolor) is available.
	 *
	 * @param string $label   Text drawn on the tile.
	 * @param int    $variant Colour variant.
	 *
	 * @return string Binary PNG data, or '' on failure.
	 */
	private static function placeholder_png_bytes( $label, $variant ) {
		$palette = [
			[ 79, 70, 229 ],
			[ 16, 185, 129 ],
			[ 249, 115, 22 ],
			[ 236, 72, 153 ],
		];
		$rgb = $palette[ $variant % count( $palette ) ];

		$width  = 1200;
		$height = 675;
		$img    = imagecreatetruecolor( $width, $height );
		$bg     = imagecolorallocate( $img, $rgb[0], $rgb[1], $rgb[2] );
		$fg     = imagecolorallocate( $img, 255, 255, 255 );
		imagefill( $img, 0, 0, $bg );

		$text = substr( (string) $label, 0, 40 );
		imagestring( $img, 5, 40, (int) ( $height / 2 ) - 10, $text, $fg );

		ob_start();
		imagepng( $img );
		$bytes = ob_get_clean();
		imagedestroy( $img );

		return (string) $bytes;
	}
